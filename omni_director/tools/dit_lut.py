"""DIT 3D Cube LUT & Color Science Suite (PM-FEAT-012).

Provides 3D Cube Look-Up Table (.cube) generation, ASC CDL transfer function baking,
DIT cart offload manifest synthesis, and scene-to-scene color grade continuity auditing.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

from omni_director.schemas import (
    AscCdlSpec,
    ColorContinuityAudit,
    ColorGamutTransform,
    DomainLutSpec,
    LutGridDimension,
    MasterProductionBible,
    SceneColorContinuityReport,
    ScenePromptSpec,
    ThreeDimensionalLutSpec,
)


def _apply_cdl_rgb(
    r: float, g: float, b: float, cdl: AscCdlSpec
) -> Tuple[float, float, float]:
    """Applies ASC CDL slope, offset, power, and saturation transfer function."""
    # Slope and offset
    r_val = max(0.0, r * cdl.slope[0] + cdl.offset[0])
    g_val = max(0.0, g * cdl.slope[1] + cdl.offset[1])
    b_val = max(0.0, b * cdl.slope[2] + cdl.offset[2])

    # Power
    r_pow = r_val ** cdl.power[0] if r_val > 0.0 else 0.0
    g_pow = g_val ** cdl.power[1] if g_val > 0.0 else 0.0
    b_pow = b_val ** cdl.power[2] if b_val > 0.0 else 0.0

    # Saturation (Rec.709 luma weights)
    luma = 0.2126 * r_pow + 0.7152 * g_pow + 0.0722 * b_pow
    sat = cdl.saturation

    r_out = max(0.0, min(1.0, luma + sat * (r_pow - luma)))
    g_out = max(0.0, min(1.0, luma + sat * (g_pow - luma)))
    b_out = max(0.0, min(1.0, luma + sat * (b_pow - luma)))

    return (r_out, g_out, b_out)


def generate_3d_lut_cube_data(
    lut_spec: Optional[ThreeDimensionalLutSpec] = None,
    cdl: Optional[AscCdlSpec] = None,
    title: Optional[str] = None,
    cube_size: Optional[int] = None,
) -> str:
    """Generates an industry-standard Adobe .cube 3D Look-Up Table content string."""
    resolved_title = title or (lut_spec.lut_title if lut_spec else "OMNI_DIRECTOR_MASTER_3DLUT")

    if cube_size is not None:
        resolved_size = cube_size
    elif lut_spec and hasattr(lut_spec.grid_dimension, "cube_size"):
        resolved_size = lut_spec.grid_dimension.cube_size
    else:
        resolved_size = 33

    resolved_cdl = cdl or (lut_spec.cdl_applied if lut_spec and lut_spec.cdl_applied else AscCdlSpec())

    domain_min = lut_spec.domain_min if lut_spec else (0.0, 0.0, 0.0)
    domain_max = lut_spec.domain_max if lut_spec else (1.0, 1.0, 1.0)
    gamut_desc = (
        lut_spec.gamut_transform.value
        if lut_spec and hasattr(lut_spec.gamut_transform, "value")
        else "ACEScg to Rec.709 Gamma 2.4"
    )

    lines = [
        f"# Adobe Cube 3D LUT - Generated by Omni Movie Director v2.6.0 DIT LUT Engine",
        f"# Color Space Transform: {gamut_desc}",
        f'TITLE "{resolved_title}"',
        f"LUT_3D_SIZE {resolved_size}",
        f"DOMAIN_MIN {domain_min[0]:.1f} {domain_min[1]:.1f} {domain_min[2]:.1f}",
        f"DOMAIN_MAX {domain_max[0]:.1f} {domain_max[1]:.1f} {domain_max[2]:.1f}",
        "",
    ]

    step = 1.0 / (resolved_size - 1) if resolved_size > 1 else 1.0

    # .cube standard order: blue changes slowest, then green, then red changes fastest
    for b_idx in range(resolved_size):
        b_in = b_idx * step
        for g_idx in range(resolved_size):
            g_in = g_idx * step
            for r_idx in range(resolved_size):
                r_in = r_idx * step
                r_out, g_out, b_out = _apply_cdl_rgb(r_in, g_in, b_in, resolved_cdl)
                lines.append(f"{r_out:.6f} {g_out:.6f} {b_out:.6f}")

    return "\n".join(lines) + "\n"


def generate_3d_cube_lut(
    bible: MasterProductionBible,
    cube_size: int = 33,
    title: str = "OMNI_DIRECTOR_MASTER_3DLUT",
) -> str:
    """Generates an industry-standard 3D .cube color grading LUT file content for a bible."""
    cdl = AscCdlSpec()
    if bible.master_color_look and bible.master_color_look.cdl:
        cdl = bible.master_color_look.cdl
    elif bible.scenes and bible.scenes[0].scene_color_look and bible.scenes[0].scene_color_look.cdl:
        cdl = bible.scenes[0].scene_color_look.cdl

    lut_spec = getattr(bible, "master_lut_spec", None) or getattr(bible, "lut_spec", None)
    if isinstance(lut_spec, ThreeDimensionalLutSpec):
        return generate_3d_lut_cube_data(lut_spec=lut_spec, cdl=cdl, title=title, cube_size=cube_size)

    return generate_3d_lut_cube_data(cdl=cdl, title=title, cube_size=cube_size)


def synthesize_default_3d_lut(
    title: str = "OMNI_DIRECTOR_MASTER_3DLUT",
    grid_dimension: LutGridDimension = LutGridDimension.GRID_33,
    gamut_transform: ColorGamutTransform = ColorGamutTransform.ACESCG_TO_REC709,
    cdl: Optional[AscCdlSpec] = None,
    colorist_notes: str = "",
) -> ThreeDimensionalLutSpec:
    """Synthesizes a fully resolved ThreeDimensionalLutSpec."""
    return ThreeDimensionalLutSpec(
        lut_title=title,
        grid_dimension=grid_dimension,
        gamut_transform=gamut_transform,
        domain_min=(0.0, 0.0, 0.0),
        domain_max=(1.0, 1.0, 1.0),
        cdl_applied=cdl or AscCdlSpec(),
        tetrahedral_interpolation=True,
        shaper_lut_enabled=False,
        colorist_notes=colorist_notes,
    )


def format_lut_prompt_token(
    lut_spec: Union[ThreeDimensionalLutSpec, DomainLutSpec, Dict[str, Any]],
    look_preset: Optional[str] = None,
) -> str:
    """Synthesizes a 3D LUT and film stock prompt token for Gemini Omni."""
    if isinstance(lut_spec, ThreeDimensionalLutSpec):
        lut_title = lut_spec.lut_title
        grid = lut_spec.grid_dimension.cube_size if hasattr(lut_spec.grid_dimension, "cube_size") else 33
        gamut = lut_spec.gamut_transform.value if hasattr(lut_spec.gamut_transform, "value") else str(lut_spec.gamut_transform)
        return f"3D LUT '{lut_title}' ({grid}x{grid}x{grid}, {gamut}, tetrahedral interpolation)"

    elif isinstance(lut_spec, DomainLutSpec):
        name = lut_spec.lut_name
        emulation = lut_spec.film_emulation
        grid = lut_spec.grid_size
        return f"Graded with {name} ({emulation} emulation, {grid}x{grid}x{grid} 3D LUT)"

    elif isinstance(lut_spec, dict):
        name = lut_spec.get("lut_title") or lut_spec.get("lut_name", "Commercial Master LUT")
        emulation = lut_spec.get("film_emulation") or lut_spec.get("gamut_transform", "ACEScg to Rec.709")
        grid = lut_spec.get("grid_size", 33)
        return f"Graded with {name} ({emulation} emulation, {grid}x{grid}x{grid} 3D LUT)"

    return "3D LUT graded (33x33x33, ACEScg to Rec.709 Gamma 2.4, tetrahedral interpolation)"


def verify_color_continuity(bible: MasterProductionBible) -> SceneColorContinuityReport:
    """Audits scene-to-scene color grade continuity across cuts."""
    if not bible.scenes or len(bible.scenes) <= 1:
        return SceneColorContinuityReport(
            is_continuous=True,
            scenes_evaluated=len(bible.scenes) if bible.scenes else 0,
            warning_messages=[],
        )

    max_slope_d = 0.0
    max_offset_d = 0.0
    max_power_d = 0.0
    max_sat_d = 0.0
    warnings = []

    prev_cdl = getattr(bible.scenes[0].scene_color_look, "cdl", AscCdlSpec()) if bible.scenes[0].scene_color_look else AscCdlSpec()

    for idx in range(1, len(bible.scenes)):
        s = bible.scenes[idx]
        cur_cdl = getattr(s.scene_color_look, "cdl", AscCdlSpec()) if s.scene_color_look else AscCdlSpec()

        # Delta slope
        s_d = max(abs(cur_cdl.slope[i] - prev_cdl.slope[i]) for i in range(3))
        o_d = max(abs(cur_cdl.offset[i] - prev_cdl.offset[i]) for i in range(3))
        p_d = max(abs(cur_cdl.power[i] - prev_cdl.power[i]) for i in range(3))
        sat_d = abs(cur_cdl.saturation - prev_cdl.saturation)

        max_slope_d = max(max_slope_d, s_d)
        max_offset_d = max(max_offset_d, o_d)
        max_power_d = max(max_power_d, p_d)
        max_sat_d = max(max_sat_d, sat_d)

        if s_d > 0.4:
            warnings.append(f"Cut {idx}->{idx+1}: Abrupt slope shift ({s_d:.2f}) exceeds broadcast tolerance.")
        if sat_d > 0.5:
            warnings.append(f"Cut {idx}->{idx+1}: Severe saturation mismatch ({sat_d:.2f}).")

        prev_cdl = cur_cdl

    is_continuous = len(warnings) == 0

    return SceneColorContinuityReport(
        is_continuous=is_continuous,
        max_slope_delta=round(max_slope_d, 3),
        max_offset_delta=round(max_offset_d, 3),
        max_power_delta=round(max_power_d, 3),
        saturation_delta=round(max_sat_d, 3),
        perceptual_delta_e_estimate=round(max_slope_d * 2.5, 2),
        warning_messages=warnings,
        scenes_evaluated=len(bible.scenes),
    )


# Alias for backward compatibility
calculate_color_continuity_audit = verify_color_continuity


def export_master_cube_lut(
    bible: MasterProductionBible,
    output_path: Optional[Union[str, Path]] = None,
    cube_size: int = 33,
) -> str:
    """Exports master 3D LUT as .cube file."""
    lut_str = generate_3d_cube_lut(bible, cube_size=cube_size)
    if output_path is not None:
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(lut_str, encoding="utf-8")
    return lut_str


def export_scene_cube_lut(
    scene: Union[ScenePromptSpec, Any],
    output_path: Optional[Union[str, Path]] = None,
    cube_size: int = 33,
) -> str:
    """Exports a scene-specific 3D LUT as .cube file."""
    cdl = scene.scene_color_look.cdl if hasattr(scene, "scene_color_look") and scene.scene_color_look else AscCdlSpec()
    title = f"SCENE_{getattr(scene, 'scene_index', 1):02d}_LUT"
    lut_spec = getattr(scene, "lut_spec", None)

    if isinstance(lut_spec, ThreeDimensionalLutSpec):
        lut_str = generate_3d_lut_cube_data(lut_spec=lut_spec, cdl=cdl, title=title, cube_size=cube_size)
    else:
        lut_str = generate_3d_lut_cube_data(cdl=cdl, title=title, cube_size=cube_size)

    if output_path is not None:
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(lut_str, encoding="utf-8")
    return lut_str


def export_dit_cart_manifest_json(
    bible: MasterProductionBible,
    output_path: Optional[Union[str, Path]] = None,
) -> str:
    """Exports DIT cart offload manifest and color pipeline metadata as JSON."""
    continuity = verify_color_continuity(bible)

    scenes_data = []
    for s in bible.scenes:
        cdl = s.scene_color_look.cdl if s.scene_color_look else AscCdlSpec()
        scenes_data.append({
            "scene_index": s.scene_index,
            "scene_title": s.scene_title,
            "look_preset": s.scene_color_look.look_preset.value if s.scene_color_look else "neutral",
            "cdl": {
                "slope": list(cdl.slope),
                "offset": list(cdl.offset),
                "power": list(cdl.power),
                "saturation": cdl.saturation,
            },
        })

    manifest = {
        "project_title": bible.project_title,
        "lut_title": "OMNI_DIRECTOR_MASTER_3DLUT",
        "cube_size": 33,
        "gamut_transform": "ACEScg to Rec.709 Gamma 2.4",
        "master_lut_file": "production_look.cube",
        "continuity_audit": continuity.model_dump(),
        "scenes": scenes_data,
    }

    json_str = json.dumps(manifest, indent=2)
    if output_path is not None:
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json_str, encoding="utf-8")
    return json_str


def export_dit_bundle(
    bible: MasterProductionBible,
    output_dir: Union[str, Path],
    cube_size: int = 33,
) -> Dict[str, str]:
    """Exports all DIT 3D LUT manifests (production_look.cube, dit_cart_manifest.json) to output_dir."""
    out_p = Path(output_dir)
    out_p.mkdir(parents=True, exist_ok=True)

    cube_p = out_p / "production_look.cube"
    manifest_p = out_p / "dit_cart_manifest.json"

    export_master_cube_lut(bible, cube_p, cube_size=cube_size)
    export_dit_cart_manifest_json(bible, manifest_p)

    return {
        "cube_lut": str(cube_p.resolve()),
        "dit_manifest": str(manifest_p.resolve()),
    }


# Alias for backward compatibility
export_lut_bundle = export_dit_bundle
